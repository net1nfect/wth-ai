def build_manifest() -> dict:
    tools = {}
    for tid, binary, category, phases, perm, go_i, apt_i, brew_i in TOOL_DEFS:
        install = {}
        if go_i:
            if go_i.startswith("go install"):
                install["go"] = go_i
            elif go_i.startswith("pip install"):
                install["pip"] = go_i
            elif go_i.startswith("npm install"):
                install["npm"] = go_i
            elif go_i.startswith("gem install"):
                install["gem"] = go_i
            elif go_i.startswith("cargo install"):
                install["cargo"] = go_i
            else:
                install["script"] = go_i
        if apt_i:
            install["apt"] = f"apt-get install -y {apt_i}"
            # RHEL/Arch fallbacks when regenerating manifest
            install.setdefault("dnf", f"dnf install -y {apt_i}")
            install.setdefault("pacman", f"pacman -S --noconfirm {apt_i}")
        if brew_i:
            install["brew"] = f"brew install {brew_i}"
            install.setdefault("scoop", f"scoop install {brew_i}")
            install.setdefault("choco", f"choco install -y {brew_i}")
        tools[tid] = {
            "binary": binary,
            "category": category,
            "phases": phases,
            "permission": perm,
            "install": install,
            "verify": f"{binary} --version" if binary not in {"php", "npm", "composer"} else f"which {binary}",
        }
    return {"version": "3.0.0", "tool_count": len(tools), "tools": tools}


if __name__ == "__main__":
    out = Path(__file__).resolve().parent / "manifest.yaml"
    data = build_manifest()
    out.write_text(yaml.dump(data, default_flow_style=False, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"Wrote {data['tool_count']} tools to {out}")
